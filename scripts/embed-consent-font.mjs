// Writes src/whoop/consent_font.ts from assets/fonts/manrope-latin.woff2.
//
// The consent page's typeface is compiled into the server instead of read from
// disk, so it is there however totem was installed (npm, a git checkout, the
// Docker image, which copies only dist/). Run after replacing the font file:
//   node scripts/embed-consent-font.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../assets/fonts/manrope-latin.woff2", import.meta.url);
const target = new URL("../src/whoop/consent_font.ts", import.meta.url);
const font = readFileSync(source);
if (font.subarray(0, 4).toString("latin1") !== "wOF2") throw new Error(`${source.pathname} is not a WOFF2 file`);
const base64 = font.toString("base64").replace(/.{1,120}/g, (line) => `  "${line}",\n`);

writeFileSync(target, `// GENERATED by scripts/embed-consent-font.mjs from assets/fonts/manrope-latin.woff2. Do not edit.
//
// Manrope (variable weight, Latin subset), the consent page's typeface.
// Copyright 2018 The Manrope Project Authors, SIL Open Font License 1.1:
// see assets/fonts/Manrope-OFL.txt.
//
// ${font.length} bytes, sha256 ${createHash("sha256").update(font).digest("hex")}

const BASE64 = [
${base64}].join("");

let decoded: Buffer | undefined;

/** The font file's bytes (WOFF2), decoded once. */
export function consentFont(): Buffer {
  return (decoded ??= Buffer.from(BASE64, "base64"));
}
`);
console.log(`wrote ${target.pathname}: ${font.length} bytes of font`);
