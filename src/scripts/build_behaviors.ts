// Regenerate src/data/behaviors.ts from saved WHOOP journal responses.
//
//   npx tsx src/scripts/build_behaviors.ts <user.json> <v3.json> [v2.json] > src/data/behaviors.ts
//
//   user.json  GET /journal-service/v2/journals/behaviors/user/{date}: the bare
//              array of full trackers (309 stock incl. 171, plus any tracked
//              custom behaviours, which are skipped: they stay live-only).
//              `GET /activities-service/v1/journals/behaviors/user` ({records})
//              works too.
//   v3.json    GET /journal-service/v3/journals/behaviors: the human category of
//              every toggle (the only source that has 171's).
//   v2.json    GET /journal-service/v2/journals/behaviors (optional): categories
//              for the 308 public records.
import { readFileSync } from "node:fs";

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => typeof v === "object" && v !== null && !Array.isArray(v);
const read = (p: string): unknown => JSON.parse(readFileSync(p, "utf8"));
const num = (v: unknown): number | null => (typeof v === "number" && Number.isFinite(v) ? v : null);
const str = (v: unknown): string | null => (typeof v === "string" && v.trim() !== "" ? v : null);

const [userPath, v3Path, v2Path] = process.argv.slice(2);
if (!userPath || !v3Path) {
  process.stderr.write("usage: build_behaviors.ts <user.json> <v3.json> [v2.json]\n");
  process.exit(2);
}

const userRaw = read(userPath);
const trackers = (Array.isArray(userRaw) ? userRaw : isObj(userRaw) && Array.isArray(userRaw.records) ? userRaw.records : []) as unknown[];

const categories = new Map<number, string>();
const v3 = read(v3Path);
for (const group of isObj(v3) && Array.isArray(v3.grouped_toggles) ? v3.grouped_toggles : []) {
  for (const t of isObj(group) && Array.isArray(group.toggles) ? group.toggles : []) {
    if (!isObj(t) || t.custom === true) continue;
    const cat = (Array.isArray(t.categories) ? t.categories : []).find((c) => typeof c === "string" && c !== "All");
    const id = Number(t.id);
    if (Number.isInteger(id) && typeof cat === "string") categories.set(id, cat);
  }
}
if (v2Path) {
  const v2 = read(v2Path);
  for (const r of isObj(v2) && Array.isArray(v2.records) ? v2.records : []) {
    if (isObj(r) && num(r.id) !== null && str(r.category)) categories.set(r.id as number, r.category as string);
  }
}

const rows = trackers.flatMap((raw) => {
  if (!isObj(raw)) return [];
  const id = num(raw.id);
  const internal = str(raw.internal_name);
  // Custom behaviours (internal_name "custom-<id>") belong to one account.
  if (id === null || !internal || internal.startsWith("custom-")) return [];
  const m = isObj(raw.magnitude) ? raw.magnitude : null;
  const type = m && (m.type === "range" || m.type === "step") ? m.type : null;
  const spec = m && type
    ? {
        type,
        label: str(m.label),
        units: str(m.units),
        minimum: num(m.minimum_inclusive),
        maximum: num(m.maximum_inclusive),
        interval: num(m.interval),
        choices: (Array.isArray(m.choices) ? m.choices : []).flatMap((c) =>
          isObj(c) && num(c.value) !== null && str(c.label) ? [{ value: c.value as number, label: c.label as string }] : []),
      }
    : null;
  return [{
    behavior_tracker_id: id,
    title: str(raw.title) ?? internal,
    question: str(raw.question_text) ?? "",
    internal_name: internal,
    category: categories.get(id) ?? "Other",
    magnitude: spec ? "magnitude" : "boolean",
    status: "active",
    behavior_type: str(raw.behavior_type) ?? "NORMAL",
    time_label: str(raw.time_label),
    magnitude_spec: spec,
  }];
}).sort((a, b) => a.behavior_tracker_id - b.behavior_tracker_id);

const out = `// AUTO-GENERATED by src/scripts/build_behaviors.ts — do not edit by hand.
// Source: GET /journal-service/v2/journals/behaviors/user/{date} (every stock
// tracker incl. 171, with its magnitude spec and time label), categories from
// GET /journal-service/v3/journals/behaviors. ${rows.length} behaviours, captured 2026-11-21.
// Custom behaviours are per-account and only ever resolved live.
import type { JournalBehavior } from "../schemas/journal.js";

export interface BehaviorMagnitudeSpec {
  /** "range": any number in [minimum, maximum]; "step": one of \`choices\`. */
  type: "range" | "step";
  label: string | null;
  units: string | null;
  minimum: number | null;
  maximum: number | null;
  interval: number | null;
  choices: Array<{ value: number; label: string }>;
}

export interface BehaviorDef extends JournalBehavior {
  behavior_type: string;
  /** Set when the behaviour also takes a time ("When was your last drink?"). */
  time_label: string | null;
  magnitude_spec: BehaviorMagnitudeSpec | null;
}

export const BEHAVIORS: readonly BehaviorDef[] = ${JSON.stringify(rows, null, 2)};

export const BEHAVIORS_BY_ID = new Map<number, BehaviorDef>(
  BEHAVIORS.map((b) => [b.behavior_tracker_id, b]),
);
export const BEHAVIORS_BY_NAME = new Map<string, BehaviorDef>(
  BEHAVIORS.map((b) => [b.internal_name, b]),
);
`;
process.stdout.write(out);
