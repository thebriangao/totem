// Regenerate src/data/sports.ts and src/data/garments.ts from WHOOP's catalogs.
//
//   npx tsx src/scripts/gen_activity_catalogs.ts <sports.json> <activity-types.json> <garments.json>
//
// Inputs are the raw response bodies of:
//   GET /activities-service/v1/sports              (current sports: id = sport_id)
//   GET /activities-service/v2/activity-types      (internal_name, score_type, category, msk_linkable; no sport_id)
//   GET /strap-location-service/v1/garment         (garment_id for create/edit)
//
// Join (SPEC.md §4.3): a type's sport is the current sport whose
// activity_type_internal_name equals the type's internal_name, else the one whose
// name equals the type's display_name (case-insensitive). Internal names are kept
// verbatim ("cheeerleading " has a typo and a trailing space on WHOOP's side).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

interface RawSport { id: number; name: string; activity_type_internal_name: string | null; is_current: boolean }
interface RawType {
  internal_name: string; display_name: string; category: string; score_type: string;
  msk_linkable: boolean; has_gps: boolean; deleted: boolean;
}
interface RawGarment {
  id: number; name: string; strap_location: string; deleted: boolean;
  strap_generation_support_info?: { supported_gen_straps?: string[] };
}

const [sportsPath, typesPath, garmentsPath] = process.argv.slice(2);
if (!sportsPath || !typesPath || !garmentsPath) {
  console.error("usage: gen_activity_catalogs.ts <sports.json> <activity-types.json> <garments.json>");
  process.exit(1);
}
const sports = (JSON.parse(readFileSync(sportsPath, "utf8")) as RawSport[]).filter((s) => s.is_current);
const types = (JSON.parse(readFileSync(typesPath, "utf8")) as RawType[]).filter((t) => !t.deleted);
const garments = (JSON.parse(readFileSync(garmentsPath, "utf8")) as RawGarment[]).filter((g) => !g.deleted);

const byInternal = new Map(sports.filter((s) => s.activity_type_internal_name).map((s) => [s.activity_type_internal_name!, s]));
const byName = new Map(sports.map((s) => [s.name.toLowerCase(), s]));

const rows = types
  .map((t) => {
    const sport = byInternal.get(t.internal_name) ?? byName.get(t.display_name.toLowerCase()) ?? null;
    return { ...t, sport_id: sport?.id ?? null };
  })
  .sort((a, b) => a.display_name.localeCompare(b.display_name) || a.internal_name.localeCompare(b.internal_name));

const q = (s: string): string => JSON.stringify(s);
const typeLines = rows.map((r) =>
  `  { internal_name: ${q(r.internal_name)}, name: ${q(r.display_name)}, sport_id: ${r.sport_id ?? "null"}, ` +
  `score_type: ${q(r.score_type)}, category: ${q(r.category)}, msk_linkable: ${r.msk_linkable}, has_gps: ${r.has_gps} },`);
const mapped = rows.filter((r) => r.sport_id !== null).length;
const today = new Date().toLocaleDateString("en-CA"); // local YYYY-MM-DD

const sportsTs = `// AUTO-GENERATED by src/scripts/gen_activity_catalogs.ts (${today}). Do not edit by hand.
// Sources: GET /activities-service/v1/sports (${sports.length} current sport ids) joined with
// GET /activities-service/v2/activity-types (${rows.length} types, ${mapped} with a sport_id).
// Non-current sport ids (-1, 50, 54, 58, 67, 68, 69, 72, 116) are left out: WHOOP rejects them.
// internal_name is verbatim; never trim it ("cheeerleading " is WHOOP's spelling).

export type ScoreType = "CARDIO" | "RECOVERY" | "SLEEP";

export interface ActivityType {
  /** The id v2 create/edit take as activity_internal_name. */
  readonly internal_name: string;
  /** Display name, as the app shows it. */
  readonly name: string;
  /** Current v0 sport id, or null (sleep, nap, and the generic "activity"). */
  readonly sport_id: number | null;
  readonly score_type: ScoreType;
  readonly category: string;
  /** A Strength Trainer workout can be linked to it. */
  readonly msk_linkable: boolean;
  readonly has_gps: boolean;
}

/** A current sport id with its v2 type. \`id\` and \`name\` keep the v1 shape. */
export interface Sport extends Omit<ActivityType, "sport_id"> {
  readonly id: number;
}

export const ACTIVITY_TYPES: readonly ActivityType[] = [
${typeLines.join("\n")}
];

export const SPORTS: readonly Sport[] = ACTIVITY_TYPES
  .filter((t): t is ActivityType & { sport_id: number } => t.sport_id !== null)
  .map(({ sport_id, ...rest }) => ({ id: sport_id, ...rest }))
  .sort((a, b) => a.id - b.id);

export const SPORTS_BY_ID = new Map<number, Sport>(SPORTS.map((s) => [s.id, s]));
export const SPORTS_BY_NAME = new Map<string, Sport>(SPORTS.map((s) => [s.name.toLowerCase(), s]));
export const ACTIVITY_TYPES_BY_INTERNAL_NAME = new Map<string, ActivityType>(ACTIVITY_TYPES.map((t) => [t.internal_name, t]));
`;

const garmentRows = garments.sort((a, b) => a.id - b.id).map((g) => {
  const gens = g.strap_generation_support_info?.supported_gen_straps ?? [];
  return `  { id: ${g.id}, name: ${q(g.name)}, strap_location: ${q(g.strap_location)}, straps: [${gens.map(q).join(", ")}] },`;
});
const garmentsTs = `// AUTO-GENERATED by src/scripts/gen_activity_catalogs.ts (${today}). Do not edit by hand.
// Source: GET /strap-location-service/v1/garment. These are the garment_id values the
// v2 create and cardio-details edit accept (WHOOP does not validate them: 99 → 200).

export interface Garment {
  readonly id: number;
  readonly name: string;
  readonly strap_location: string;
  /** Strap generations that support it (GEN_4 only for 12–15). */
  readonly straps: readonly string[];
}

export const GARMENTS: readonly Garment[] = [
${garmentRows.join("\n")}
];

export const GARMENTS_BY_ID = new Map<number, Garment>(GARMENTS.map((g) => [g.id, g]));
`;

const dataDir = join(dirname(fileURLToPath(import.meta.url)), "..", "data");
writeFileSync(join(dataDir, "sports.ts"), sportsTs);
writeFileSync(join(dataDir, "garments.ts"), garmentsTs);
console.log(`sports.ts: ${rows.length} types, ${mapped} sport ids; garments.ts: ${garmentRows.length} garments`);
